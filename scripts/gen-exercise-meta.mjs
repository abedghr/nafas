// Generates server/modules/workout/seed-data/exercise-meta.map.ts:
//   EXERCISE_EQUIPMENT (derived from the exercise name, deterministic)
//   EXERCISE_IMAGE     (matched to the PUBLIC-DOMAIN free-exercise-db images)
// free-exercise-db is Unlicense (public domain) → its images are free to use.
// Run: node scripts/gen-exercise-meta.mjs
import fs from 'fs';

const DATASET = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';
const IMG_BASE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/';

// our full name list = existing seed names (file) + the Hevy screenshot names
const existing = fs.readFileSync('/tmp/existing_ex.txt', 'utf8').split('\n').map(s => s.trim()).filter(Boolean);
const hevy = fs.readFileSync('/tmp/hevy_ex.txt', 'utf8').split('\n').map(s => s.trim()).filter(Boolean);
const names = [...new Set([...existing, ...hevy])].sort();

// ── equipment from the name (Hevy's 9 buckets) ──────────────────────────────
function equipOf(raw) {
  const n = raw.toLowerCase();
  if (/\bsmith\b/.test(n)) return 'Machine';
  if (/\(machine|\bmachine\b|treadmill|rowing machine|stair machine|recumbent|ski erg|spinning|stationary|elliptical|assault bike|leg press|pendulum|vertical traction|seated dip machine|hack squat|lat pulldown|pulldown|cable|pushdown|pressdown|\brope\b/.test(n)) return 'Machine';
  if (/\bbarbell\b|pendlay|\bdeadlift\b|romanian deadlift|sumo deadlift|zercher|power clean|hang clean|clean & jerk|power snatch|\bsnatch\b|split jerk|press under|rack pull|overhead press \(barbell/.test(n) && !/dumbbell/.test(n)) return 'Barbell';
  if (/\bdumbbell\b/.test(n)) return 'Dumbbell';
  if (/\bkettlebell\b/.test(n)) return 'Kettlebell';
  if (/\bplate\b/.test(n)) return 'Plate';
  if (/\bband\b|resistance band/.test(n)) return 'Resistance Band';
  if (/\bsuspension\b|\btrx\b/.test(n)) return 'Suspension Band';
  if (/\bsled\b|\btire\b|sandbag|wall ball|wrist roller|farmer|suitcase|battle rope/.test(n)) return 'Other';
  return 'None'; // bodyweight / calisthenics / cardio-no-machine / holds
}

// ── image match against the public-domain dataset ───────────────────────────
const norm = (s) => s.toLowerCase()
  .replace(/\([^)]*\)/g, ' ')                 // drop equipment parens
  .replace(/\b(barbell|dumbbell|cable|machine|smith|kettlebell|plate|band|suspension|weighted|assisted|bodyweight)\b/g, ' ')
  .replace(/[^a-z0-9]+/g, ' ').trim().replace(/\s+/g, ' ');

const res = await fetch(DATASET);
const data = await res.json();
const byNorm = new Map();
for (const e of data) {
  if (!e.images || !e.images.length) continue;
  const k = norm(e.name);
  if (!byNorm.has(k)) byNorm.set(k, IMG_BASE + e.images[0]);
}

const equip = {}, image = {};
let matched = 0;
for (const name of names) {
  equip[name] = equipOf(name);
  const url = byNorm.get(norm(name));
  if (url) { image[name] = url; matched++; }
}

const q = (s) => JSON.stringify(s);
let out = `// AUTO-GENERATED by scripts/gen-exercise-meta.mjs — do not hand-edit.
// EXERCISE_EQUIPMENT: derived from the name. EXERCISE_IMAGE: matched to the
// PUBLIC-DOMAIN free-exercise-db (Unlicense) — free to use; NOT Hevy's images.
export const EXERCISE_EQUIPMENT: Record<string, string> = {
${names.map(n => `  ${q(n)}: ${q(equip[n])},`).join('\n')}
};

export const EXERCISE_IMAGE: Record<string, string> = {
${Object.keys(image).sort().map(n => `  ${q(n)}: ${q(image[n])},`).join('\n')}
};
`;
fs.writeFileSync('server/modules/workout/seed-data/exercise-meta.map.ts', out);
console.log(`names ${names.length} | equipment set ${names.length} | images matched ${matched}`);
